    def _save_adv_evo_record(
        self,
        model_pair,
        suite_name,
        user_task_id,
        injection_task_id,
        attacker_messages,
        injection_records,
        attacker_reward,
        defender_result,
        population_attribution,
    ) -> None:
        path = f"{self._rollout_save_dir}/adv_evo_rollouts_{__import__('os').getpid()}.jsonl"
        record = {
            "ts": time.time(),
            "model_pair": model_pair,
            "suite_name": suite_name,
            "user_task_id": user_task_id,
            "injection_task_id": injection_task_id,
            "population_attribution": dict(population_attribution),
            "attacker": {
                "messages": attacker_messages,
                "injections": injection_records,
                "num_turns": sum(msg.get("role") == "assistant" for msg in attacker_messages),
                "reward": attacker_reward,
            },
            "defender": {
                "messages": defender_result["messages"],
                "num_turns": defender_result["num_turns"],
                "tool_call_count": defender_result["tool_call_count"],
                "asr_success": defender_result["asr_success"],
                "utility_failed": defender_result["utility_failed"],
                "sample_valid": bool(defender_result.get("sample_valid", False)),
                "invalid_reason": defender_result.get("invalid_reason"),
                "evaluator_error": defender_result.get("evaluator_error"),
                "exact_trace_drops": defender_result.get("exact_trace_drops", 0),
                "train_sequence_tokens": defender_result.get("train_sequence_tokens"),
                "train_sequence_overflow": bool(
                    defender_result.get("train_sequence_overflow", False)
                ),
                "tool_response_stats": {
                    key: defender_result.get(key, 0)
                    for key in (
                        "num_tool_responses",
                        "num_tool_responses_truncated",
                        "num_payloads_inserted",
                        "num_payloads_survived_truncation",
                        "num_payloads_truncated",
                        "tool_response_chars_before",
                        "tool_response_chars_after",
                    )
                },
            },
        }
        try:
            with open(path, "a", encoding="utf-8") as handle:
                handle.write(json.dumps(record, ensure_ascii=False, default=str) + "\n")
        except Exception as exc:
            logger.warning("Failed to save adv-evo rollout: %s", exc)
