"""SFT-aligned adaptive multi-injection loop for adversarial co-evolution.

The legacy co-training loop samples one attacker payload before the defender
starts and reuses it for every injection vector.  This loop mirrors the online
interaction that produced ``attacker_sft_final*.jsonl`` instead:

* start the AgentDojo environment with a placeholder in every injection vector;
* wait until the defender actually reads a placeholder-bearing tool result;
* generate one attacker turn from the SFT system/user prompt format;
* replace only that injection point and continue the same defender trajectory;
* retain the attacker conversation so later turns can adapt to earlier failures.

Only tokens generated by the attacker are marked in ``response_mask``.  System
messages, user observations, defender trajectories and ChatML framing tokens are
context-only.  This makes one environment rollout a genuine multi-action PPO
trajectory while avoiding N independent defender reruns for N injection points.
"""

